#Crea un programa que convierta una temperatura dada en grados celsisus a grados fahrenheit.Muestra en pantalla el resultado de la coversion

gradoscel=float(input("Ingresa los grados celsius que deseas convertir: "))

fahremheit=(gradoscel*1.8) + 32

print(f"Los grados celsius que deseas convertir son: {gradoscel} y la conversion a Grados Fahrenheit son: {fahremheit}")